const generatedHeader = "// Code generated by protoc-gen-veloce. DO NOT EDIT."

type module struct {
	file     *protogen.File
	g        *protogen.GeneratedFile
	prefix   string
	exports  []string
	declared map[string]bool
	names    map[protoreflect.FullName]string
	runtime  map[string]string
	imports  map[string][]string
	rules    map[protoreflect.FullName][]string
	rpcs     []*protogen.Method
	rpcNames map[*protogen.Method]string
	hasRPCs  bool
	hasRules bool
}

// P writes a line to the module's output file.
func (m *module) P(v ...any) {
	m.g.P(v...)
}

// generateFile emits the TypeScript module for one proto file.
func generateFile(gen *protogen.Plugin, file *protogen.File) (*module, error) {
	m := &module{
		file:     file,
		prefix:   tsPrefix(file),
		declared: map[string]bool{},
		names:    map[protoreflect.FullName]string{},
		runtime:  map[string]string{},
		imports:  map[string][]string{},
		rules:    map[protoreflect.FullName][]string{},
		rpcNames: map[*protogen.Method]string{},
	}
	if err := m.declareTypes(); err != nil {
		return nil, err
	}
	if err := m.collectRules(); err != nil {
		return nil, err
	}
	m.collectRPCs()
	if err := m.declareRPCs(); err != nil {
		return nil, err
	}
	m.resolveRuntimeImports()
	m.resolveReferences()

	m.g = gen.NewGeneratedFile(m.prefix+".ts", "")
	m.P(generatedHeader)
	m.P("// source: ", file.Desc.Path())
	m.P()
	m.emitImports()

	for _, enum := range file.Enums {
		m.generateEnum(enum)
	}
	m.forEachMessage(func(msg *protogen.Message) {
		for _, enum := range msg.Enums {
			m.generateEnum(enum)
		}
		m.generateMessage(msg)
	})
	m.forEachMessage(func(msg *protogen.Message) {
		if entries := m.rules[msg.Desc.FullName()]; len(entries) > 0 {
			m.generateMessageRules(msg, entries)
		}
	})
	for _, method := range m.rpcs {
		m.generateRPC(method)
	}
	return m, nil
}

// forEachMessage visits every non-map-entry message in declaration order, parents first.
func (m *module) forEachMessage(fn func(msg *protogen.Message)) {
	var walk func(messages []*protogen.Message)
	walk = func(messages []*protogen.Message) {
		for _, msg := range messages {
			if msg.Desc.IsMapEntry() {
				continue
			}
			fn(msg)
			walk(msg.Messages)
		}
	}
	walk(m.file.Messages)
}

// declare reserves a top-level identifier in the module, failing on duplicates.
func (m *module) declare(name string, exported bool) error {
	if m.declared[name] {
		return fmt.Errorf("%s: the TypeScript name %q is generated twice; rename one of the proto types or RPCs", m.file.Desc.Path(), name)
	}
	m.declared[name] = true
	if exported {
		m.exports = append(m.exports, name)
	}
	return nil
}

func (m *module) declareTypes() error {
	declareEnum := func(enum *protogen.Enum) error {
		m.names[enum.Desc.FullName()] = enum.GoIdent.GoName
		exported, internal := enumNames(enum)
		for _, n := range exported {
			if err := m.declare(n, true); err != nil {
				return err
			}
		}
		for _, n := range internal {
			if err := m.declare(n, false); err != nil {
				return err
			}
		}
		return nil
	}
	for _, enum := range m.file.Enums {
		if err := declareEnum(enum); err != nil {
			return err
		}
	}
	var err error
	m.forEachMessage(func(msg *protogen.Message) {
		if err != nil {
			return
		}
		for _, enum := range msg.Enums {
			if err = declareEnum(enum); err != nil {
				return
			}
		}
		m.names[msg.Desc.FullName()] = msg.GoIdent.GoName
		err = m.declare(msg.GoIdent.GoName, true)
	})
	return err
}

func (m *module) collectRules() error {
	var err error
	m.forEachMessage(func(msg *protogen.Message) {
		if err != nil {
			return
		}
		if entries := messageRuleEntries(msg); len(entries) > 0 {
			m.rules[msg.Desc.FullName()] = entries
			m.hasRules = true
			err = m.declare(msg.GoIdent.GoName+"Rules", true)
		}
	})
	return err
}

func (m *module) collectRPCs() {
	for _, svc := range m.file.Services {
		for _, method := range svc.Methods {
			if isSupportedMethod(method) {
				m.rpcs = append(m.rpcs, method)
			}
		}
	}
	m.hasRPCs = len(m.rpcs) > 0
}

// declareRPCs names one function per RPC: the lowerCamel method name, or the service-qualified
// name when that would be a reserved word, clash with another generated name, or repeat across services.
func (m *module) declareRPCs() error {
	counts := map[string]int{}
	for _, method := range m.rpcs {
		counts[lowerCamel(string(method.Desc.Name()))]++
	}
	for _, method := range m.rpcs {
		name := lowerCamel(string(method.Desc.Name()))
		if reservedWords[name] || counts[name] > 1 || m.declared[name] {
			name = lowerCamel(string(method.Parent.Desc.Name())) + string(method.Desc.Name())
		}
		if err := m.declare(name, true); err != nil {
			return err
		}
		m.rpcNames[method] = name
	}
	return nil
}

func (m *module) resolveRuntimeImports() {
	add := func(name string) {
		local := name
		for m.declared[local] {
			local = "$" + local
		}
		m.runtime[name] = local
	}
	if m.hasRPCs {
		add("VeloceClient")
		add("RequestOptions")
	}
	if m.hasRules {
		add("MessageRules")
	}
}

// resolveReferences assigns a local identifier to every type defined in another file that this
// module references, aliasing it when the plain name is already taken.
func (m *module) resolveReferences() {
	taken := map[string]bool{}
	for name := range m.declared {
		taken[name] = true
	}
	for _, local := range m.runtime {
		taken[local] = true
	}

	refer := func(desc protoreflect.Descriptor, goName string) {
		if _, ok := m.names[desc.FullName()]; ok {
			return
		}
		local := goName
		if taken[local] {
			local = strings.ReplaceAll(string(desc.ParentFile().Package()), ".", "_") + "_" + goName
		}
		for taken[local] {
			local = "$" + local
		}
		taken[local] = true
		m.names[desc.FullName()] = local
		spec := goName
		if local != goName {
			spec = goName + " as " + local
		}
		filePath := desc.ParentFile().Path()
		m.imports[filePath] = append(m.imports[filePath], spec)
	}

	var referField func(field *protogen.Field)
	referField = func(field *protogen.Field) {
		if field.Desc.IsMap() {
			referField(field.Message.Fields[1])
			return
		}
		if field.Enum != nil {
			refer(field.Enum.Desc, field.Enum.GoIdent.GoName)
		}
		if field.Message != nil {
			refer(field.Message.Desc, field.Message.GoIdent.GoName)
		}
	}

	m.forEachMessage(func(msg *protogen.Message) {
		if _, ok := wktAlias(msg); ok {
			return
		}
		for _, field := range msg.Fields {
			referField(field)
		}
	})
	for _, method := range m.rpcs {
		refer(method.Input.Desc, method.Input.GoIdent.GoName)
		for _, p := range bindingFor(method).pathParams {
			if p.leaf != nil {
				referField(p.leaf)
			}
		}
		if isHTTPBody(method.Output) {
			continue
		}
		if f := bindingFor(method).responseBody; f != nil {
			referField(f)
			continue
		}
		refer(method.Output.Desc, method.Output.GoIdent.GoName)
	}
}

func (m *module) emitImports() {
	wrote := false
	runtimeImport := func(prefix string, names ...string) {
		var specs []string
		for _, n := range names {
			local, ok := m.runtime[n]
			if !ok {
				continue
			}
			if local == n {
				specs = append(specs, n)
			} else {
				specs = append(specs, n+" as "+local)
			}
		}
		if len(specs) > 0 {
			m.P("import type { ", strings.Join(specs, ", "), " } from \"", relativeImportPath(m.prefix, prefix), "\";")
			wrote = true
		}
	}
	runtimeImport(runtimeFilePrefix, "VeloceClient", "RequestOptions")
	runtimeImport(validateFilePrefix, "MessageRules")

	paths := make([]string, 0, len(m.imports))
	for p := range m.imports {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		target := strings.TrimSuffix(p, ".proto")
		m.P("import type { ", strings.Join(m.imports[p], ", "), " } from \"", relativeImportPath(m.prefix, target), "\";")
		wrote = true
	}
	if wrote {
		m.P()
	}
}

// typeName is the local TypeScript identifier for a message or enum.
func (m *module) typeName(desc protoreflect.Descriptor) string {
	return m.names[desc.FullName()]
}

func (m *module) generateMessage(msg *protogen.Message) {
	name := msg.GoIdent.GoName
	if alias, ok := wktAlias(msg); ok {
		m.P("export type ", name, " = ", alias, ";")
		m.P()
		return
	}
	if len(msg.Fields) == 0 {
		m.P("export type ", name, " = { [key: string]: never };")
		m.P()
		return
	}

	complete := wireComplete(msg)
	m.P("export interface ", name, " {")
	for _, field := range msg.Fields {
		shape := shapeOf(field, complete)
		mark := ""
		if shape.optional {
			mark = "?"
		}
		tsType := m.fieldType(field)
		if shape.nullable {
			tsType += " | null"
		}
		m.P("  ", propName(field.Desc.JSONName()), mark, ": ", tsType, ";")
	}
	m.P("}")
	m.P()
}

// wktAlias maps a Well-Known Type to the TypeScript shape of its canonical JSON encoding.
func wktAlias(msg *protogen.Message) (string, bool) {
	if msg.Desc.ParentFile().Package() != "google.protobuf" {
		return "", false
	}
	switch msg.Desc.Name() {
	case "Timestamp", "Duration", "FieldMask", "StringValue", "BytesValue", "Int64Value", "UInt64Value":
		return "string", true
	case "Int32Value", "UInt32Value", "FloatValue", "DoubleValue":
		return "number", true
	case "BoolValue":
		return "boolean", true
	case "Struct":
		return "{ [key: string]: Value }", true
	case "Value":
		return "null | boolean | number | string | Value[] | { [key: string]: Value }", true
	case "ListValue":
		return "Value[]", true
	case "Empty":
		return "{ [key: string]: never }", true
	case "Any":
		return "{ \"@type\": string; [key: string]: unknown }", true
	}
	return "", false
}

type fieldShape struct {
	optional bool
	nullable bool
}

// wireComplete reports whether a message's JSON is expected to carry every non-oneof field,
// which holds for responses from grpc-gateway's default marshaler (EmitUnpopulated).
func wireComplete(msg *protogen.Message) bool {
	switch opts.fieldPresence {
	case PresenceRequired:
		return true
	case PresenceSplit:
		return isResponseOnlyMessage(msg)
	}
	return false
}

// shapeOf decides whether a field is optional and whether it may be null. With EmitUnpopulated,
// unset oneof members are omitted and unset fields with explicit presence (messages, proto2
// optional) are written as null. Protovalidate `required` and proto2 `required` fields are always
// present and non-null.
func shapeOf(field *protogen.Field, complete bool) fieldShape {
	if rules := fieldRules(field); rules != nil && rules.GetRequired() {
		return fieldShape{}
	}
	if field.Desc.Cardinality() == protoreflect.Required {
		return fieldShape{}
	}
	inOneof := field.Desc.ContainingOneof() != nil
	tracked := field.Desc.HasPresence() && !inOneof
	if complete {
		return fieldShape{optional: inOneof, nullable: tracked}
	}
	return fieldShape{optional: true, nullable: tracked && opts.fieldPresence == PresenceSplit}
}

func (m *module) fieldType(field *protogen.Field) string {
	if field.Desc.IsMap() {
		return "{ [key: string]: " + m.baseType(field.Message.Fields[1]) + " }"
	}
	if field.Desc.IsList() {
		return m.baseType(field) + "[]"
	}
	return m.baseType(field)
}

func (m *module) baseType(field *protogen.Field) string {
	switch field.Desc.Kind() {
	case protoreflect.BoolKind:
		return "boolean"
	case protoreflect.Int32Kind, protoreflect.Uint32Kind, protoreflect.Sint32Kind,
		protoreflect.Fixed32Kind, protoreflect.Sfixed32Kind, protoreflect.FloatKind, protoreflect.DoubleKind:
		return "number"
	case protoreflect.Int64Kind, protoreflect.Uint64Kind, protoreflect.Sint64Kind,
		protoreflect.Fixed64Kind, protoreflect.Sfixed64Kind, protoreflect.StringKind, protoreflect.BytesKind:
		return "string"
	case protoreflect.EnumKind:
		return m.typeName(field.Enum.Desc)
	case protoreflect.MessageKind, protoreflect.GroupKind:
		return m.typeName(field.Message.Desc)
	}
	return "unknown"
}

// acceptsEmpty reports whether `{}` is a valid value of the message's type, so the RPC can
// default its request argument.
func acceptsEmpty(msg *protogen.Message) bool {
	if alias, ok := wktAlias(msg); ok {
		return strings.HasPrefix(alias, "{ [key: string]: never }")
	}
	complete := wireComplete(msg)
	for _, field := range msg.Fields {
		if !shapeOf(field, complete).optional {
			return false
		}
	}
	return true
}

// isSupportedMethod reports whether an RPC can be called over grpc-gateway with fetch; client
// and bidirectional streaming cannot.
func isSupportedMethod(method *protogen.Method) bool {
	return !method.Desc.IsStreamingClient()
}

func isHTTPBody(msg *protogen.Message) bool {
	return msg.Desc.FullName() == "google.api.HttpBody"
}

type httpBinding struct {
	method       string
	path         string
	body         string
	responseBody *protogen.Field
	pathParams   []pathParam
}

type pathParam struct {
	jsonPath string
	leaf     *protogen.Field
}

// bindingFor resolves an RPC's google.api.http rule, rewriting field paths to their JSON names.
// Unannotated RPCs fall back to POST /package.Service/Method with the request as the body.
func bindingFor(method *protogen.Method) httpBinding {
	b := httpBinding{
		method: "POST",
		path:   fmt.Sprintf("/%s/%s", method.Parent.Desc.FullName(), method.Desc.Name()),
		body:   "*",
	}
	rule, ok := proto.GetExtension(method.Desc.Options(), annotations.E_Http).(*annotations.HttpRule)
	if !ok || rule == nil || rule.GetPattern() == nil {
		return b
	}
	switch p := rule.GetPattern().(type) {
	case *annotations.HttpRule_Get:
		b.method, b.path = "GET", p.Get
	case *annotations.HttpRule_Post:
		b.method, b.path = "POST", p.Post
	case *annotations.HttpRule_Put:
		b.method, b.path = "PUT", p.Put
	case *annotations.HttpRule_Delete:
		b.method, b.path = "DELETE", p.Delete
	case *annotations.HttpRule_Patch:
		b.method, b.path = "PATCH", p.Patch
	case *annotations.HttpRule_Custom:
		b.method, b.path = strings.ToUpper(p.Custom.GetKind()), p.Custom.GetPath()
	}
	b.path, b.pathParams = rewritePath(method.Input, b.path)
	switch body := rule.GetBody(); body {
	case "", "*":
		b.body = body
	default:
		b.body, _ = jsonFieldPath(method.Input, body)
	}
	if rb := rule.GetResponseBody(); rb != "" {
		b.responseBody = findField(method.Output, rb)
	}
	return b
}

// rewritePath converts `{field.path=pattern}` variables to JSON field names. A lone `*` pattern
// is dropped because it binds a single segment, the same as no pattern.
func rewritePath(msg *protogen.Message, tmpl string) (string, []pathParam) {
	var b strings.Builder
	var params []pathParam
	for {
		open := strings.IndexByte(tmpl, '{')
		if open < 0 {
			break
		}
		end := strings.IndexByte(tmpl[open:], '}')
		if end < 0 {
			break
		}
		end += open
		b.WriteString(tmpl[:open])
		field, pattern, hasPattern := strings.Cut(tmpl[open+1:end], "=")
		jsonPath, leaf := jsonFieldPath(msg, strings.TrimSpace(field))
		params = append(params, pathParam{jsonPath: jsonPath, leaf: leaf})
		b.WriteString("{")
		b.WriteString(jsonPath)
		if hasPattern && pattern != "*" {
			b.WriteString("=")
			b.WriteString(pattern)
		}
		b.WriteString("}")
		tmpl = tmpl[end+1:]
	}
	b.WriteString(tmpl)
	return b.String(), params
}

// jsonFieldPath maps a dotted proto field path to the dotted JSON names used on the wire, and
// returns the field the path ends at when it resolves.
func jsonFieldPath(msg *protogen.Message, protoPath string) (string, *protogen.Field) {
	parts := strings.Split(protoPath, ".")
	var leaf *protogen.Field
	for i, p := range parts {
		leaf = findField(msg, p)
		if leaf == nil {
			parts[i] = snakeToCamel(p)
			msg = nil
			continue
		}
		parts[i] = leaf.Desc.JSONName()
		msg = leaf.Message
	}
	return strings.Join(parts, "."), leaf
}

func findField(msg *protogen.Message, name string) *protogen.Field {
	if msg == nil {
		return nil
	}
	for _, f := range msg.Fields {
		if string(f.Desc.Name()) == name {
			return f
		}
	}
	return nil
}

func (m *module) generateRPC(method *protogen.Method) {
	b := bindingFor(method)
	client := m.runtime["VeloceClient"]
	reqOpts := m.runtime["RequestOptions"]

	param := "request: " + m.typeName(method.Input.Desc)
	if len(b.pathParams) > 0 {
		param += " & " + m.pathParamsType(b.pathParams)
	} else if acceptsEmpty(method.Input) {
		param += " = {}"
	}

	rpc := "{ method: " + jsString(b.method) + ", path: " + jsString(b.path)
	if b.body != "" {
		rpc += ", body: " + jsString(b.body)
	}
	if opts.debugMethodHeader {
		rpc += ", grpcMethod: " + jsString(fmt.Sprintf("/%s/%s", method.Parent.Desc.FullName(), method.Desc.Name()))
	}
	rpc += " }"

	var result, call string
	switch {
	case isHTTPBody(method.Output):
		result = "Promise<globalThis.Response>"
		call = "client.raw("
	default:
		out := m.typeName(method.Output.Desc)
		if f := b.responseBody; f != nil {
			out = m.fieldType(f)
			if shapeOf(f, true).nullable {
				out += " | null"
			}
		}
		if method.Desc.IsStreamingServer() {
			result = "AsyncGenerator<" + out + ", void, undefined>"
			call = "client.stream<" + out + ">("
		} else {
			result = "Promise<" + out + ">"
			call = "client.unary<" + out + ">("
		}
	}

	m.P("export function ", m.rpcNames[method], "(client: ", client, ", ", param, ", options?: ", reqOpts, "): ", result, " {")
	m.P("  return ", call, rpc, ", request, options);")
	m.P("}")
	m.P()
}

type pathNode struct {
	keys     []string
	children map[string]*pathNode
	leaf     *protogen.Field
}

// pathParamsType renders the object type that makes every path-bound field required, so a
// call missing a URL parameter fails to compile instead of at request time.
func (m *module) pathParamsType(params []pathParam) string {
	root := &pathNode{children: map[string]*pathNode{}}
	for _, p := range params {
		node := root
		for _, key := range strings.Split(p.jsonPath, ".") {
			child, ok := node.children[key]
			if !ok {
				child = &pathNode{children: map[string]*pathNode{}}
				node.children[key] = child
				node.keys = append(node.keys, key)
			}
			node = child
		}
		node.leaf = p.leaf
	}
	var render func(n *pathNode) string
	render = func(n *pathNode) string {
		parts := make([]string, 0, len(n.keys))
		for _, key := range n.keys {
			child := n.children[key]
			t := "string"
			switch {
			case len(child.keys) > 0:
				t = render(child)
			case child.leaf != nil:
				t = m.fieldType(child.leaf)
			}
			parts = append(parts, propName(key)+": "+t)
		}
		return "{ " + strings.Join(parts, "; ") + " }"
	}
	return render(root)
}

var identifierPattern = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

// propName renders a property key, quoting it when it is not a plain identifier.
func propName(name string) string {
	if identifierPattern.MatchString(name) {
		return name
	}
	return jsString(name)
}

// jsString renders a Go string as a double-quoted TypeScript string literal.
func jsString(s string) string {
	return "\"" + tsEscape(s) + "\""
}

// tsEscape escapes a Go string for embedding in a double-quoted TypeScript literal.
func tsEscape(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		case ' ':
			b.WriteString(` `)
		case ' ':
			b.WriteString(` `)
		default:
			if r < 0x20 || r == 0x7f {
				fmt.Fprintf(&b, `\u%04x`, r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	return b.String()
}

// lowerCamel lowercases a leading word, keeping acronyms intact: ListItems → listItems,
// HTTPConfig → httpConfig, ID → id.
func lowerCamel(s string) string {
	runes := []rune(s)
	n := 0
	for n < len(runes) && unicode.IsUpper(runes[n]) {
		n++
	}
	if n > 1 && n < len(runes) {
		n--
	}
	for i := 0; i < n; i++ {
		runes[i] = unicode.ToLower(runes[i])
	}
	return string(runes)
}

func snakeToCamel(s string) string {
	var b strings.Builder
	upper := false
	for _, c := range s {
		if c == '_' {
			upper = true
			continue
		}
		if upper {
			b.WriteRune(unicode.ToUpper(c))
			upper = false
		} else {
			b.WriteRune(c)
		}
	}
	return b.String()
}

// relativeImportPath is the ESM specifier from one generated module to another.
func relativeImportPath(fromPrefix, toPrefix string) string {
	rel := relPath(path.Dir(fromPrefix), toPrefix)
	if !strings.HasPrefix(rel, ".") {
		rel = "./" + rel
	}
	return rel + opts.importExtension
}

func relPath(fromDir, to string) string {
	from := splitPath(fromDir)
	target := splitPath(to)
	i := 0
	for i < len(from) && i < len(target)-1 && from[i] == target[i] {
		i++
	}
	parts := make([]string, 0, len(from)-i+len(target)-i)
	for range from[i:] {
		parts = append(parts, "..")
	}
	parts = append(parts, target[i:]...)
	return strings.Join(parts, "/")
}

func splitPath(p string) []string {
	if p == "." || p == "" {
		return nil
	}
	return strings.Split(p, "/")
}

